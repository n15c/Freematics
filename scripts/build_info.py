# PlatformIO pre-build script: generates build_info.h with a build number.
# Build number = number of git commits on the current branch, so every pushed
# change gets a higher number. "+" marks a build with uncommitted changes.
Import("env")
import datetime
import os
import subprocess


def git(*args):
    try:
        return subprocess.check_output(["git"] + list(args), cwd=env.subst("$PROJECT_DIR"),
                                       stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return ""


build = git("rev-list", "--count", "HEAD") or "0"
commit = git("rev-parse", "--short", "HEAD") or "unknown"
if git("status", "--porcelain", "--untracked-files=no"):
    commit += "+"
# commit time orders builds across branches and squash merges (used by the auto update)
epoch = git("log", "-1", "--format=%ct") or "0"
pioenv = env.subst("$PIOENV")
# branch: in GitHub Actions from GITHUB_REF_NAME (pull requests: head branch)
branch = os.environ.get("GITHUB_HEAD_REF") or os.environ.get("GITHUB_REF_NAME") or git("rev-parse", "--abbrev-ref", "HEAD") or "unknown"
stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

content = (
    "// generated by scripts/build_info.py - do not edit\n"
    "#pragma once\n"
    "#define FW_BUILD %s\n"
    "#define FW_COMMIT \"%s\"\n"
    "#define FW_BUILD_TIME \"%s\"\n"
    "#define FW_COMMIT_EPOCH %s\n"
    "#define FW_ENV \"%s\"\n"
    "#define FW_BRANCH \"%s\"\n" % (build, commit, stamp, epoch, pioenv, branch)
)

gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
os.makedirs(gen_dir, exist_ok=True)
path = os.path.join(gen_dir, "build_info.h")
old = open(path).read() if os.path.exists(path) else ""
if old != content:
    with open(path, "w") as f:
        f.write(content)
env.Append(CPPPATH=[gen_dir])
print("Firmware build %s (%s)" % (build, commit))
